/**
 * Generates `src/generated/content-meta.ts` — a build-time snapshot of
 * reading time + table-of-contents for every MDX file in content/blogs and
 * content/projects.
 *
 * Runs automatically before `next build` (see package.json) so production
 * never needs to read MDX files from disk at request time (Fumadocs'
 * `page.data.content` getter does exactly that and fails on Vercel lambdas).
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import matter from "gray-matter";
import readingTime from "reading-time";
import { getTableOfContents } from "fumadocs-core/server";

const ROOT = path.resolve(process.cwd());
const OUT_DIR = path.join(ROOT, "generated", "mdx");
const OUT_FILE = path.join(OUT_DIR, "index.ts");

const COLLECTIONS = [
  { dir: "content/blogs", exportName: "blogMeta" },
  { dir: "content/projects", exportName: "projectMeta" },
];

async function collect(dir) {
  const fullDir = path.join(ROOT, dir);
  const files = (await readdir(fullDir)).filter((f) => /\.mdx?$/.test(f));
  const meta = {};

  for (const file of files) {
    const slug = file.replace(/\.mdx?$/, "");
    try {
      const raw = await readFile(path.join(fullDir, file), "utf8");
      const { content } = matter(raw);
      const toc = getTableOfContents(content).map((item) => ({
        id: item.url.replace(/^#/, ""),
        label: typeof item.title === "string" ? item.title : "",
        depth: item.depth,
      }));
      meta[slug] = {
        readingTime: readingTime(content).text,
        toc,
      };
    } catch (err) {
      console.warn(`[content-meta] skip ${dir}/${file}: ${err.message}`);
    }
  }
  return meta;
}

const collections = {};
for (const { dir, exportName } of COLLECTIONS) {
  collections[exportName] = await collect(dir);
}

const header = `// AUTO-GENERATED by scripts/generate-content-meta.mjs — do not edit.
// Snapshot of reading time + table of contents per content file, computed
// at build time so runtime rendering never touches the filesystem.

export interface TocItem {
  id: string;
  label: string;
  depth: number;
}

export interface ContentMeta {
  readingTime: string;
  toc: TocItem[];
}
`;

let body = header;
for (const { exportName } of COLLECTIONS) {
  body += `\nexport const ${exportName}: Record<string, ContentMeta> = ${JSON.stringify(
    collections[exportName],
    null,
    2,
  )};\n`;
}

await mkdir(OUT_DIR, { recursive: true });
await writeFile(OUT_FILE, body, "utf8");
console.log(`[content-meta] wrote ${OUT_FILE}`);
